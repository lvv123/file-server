#!/usr/bin/env python3
"""Generate src/static_assets.cpp from the files in web/.

The web UI is embedded into the binary so that deployment stays "one
executable + one config file + one data directory".  Run this script after
editing anything under web/ (or configure the build with
-DREGENERATE_ASSETS=ON).
"""

from __future__ import annotations

import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "src" / "static_assets.cpp"

ASSETS = [
    ("/", "index.html", "text/html; charset=utf-8"),
    ("/index.html", "index.html", "text/html; charset=utf-8"),
    ("/app.js", "app.js", "application/javascript; charset=utf-8"),
    ("/style.css", "style.css", "text/css; charset=utf-8"),
]

HEX_DIGITS = set("0123456789abcdefABCDEF")


def string_tokens(data: bytes) -> list[str]:
    """Turn raw bytes into C++ string-literal chunks.

    Non printable bytes become ``\\xNN`` escapes.  Because a hex escape greedily
    consumes following hex digits, an empty literal is inserted whenever a
    literal character that happens to be a hex digit follows an escape.
    """
    tokens: list[str] = []
    previous_was_escape = False

    for byte in data:
        char = chr(byte)
        is_printable = 0x20 <= byte <= 0x7E and char not in {'"', "\\", "?"}
        if is_printable:
            if previous_was_escape and char in HEX_DIGITS:
                tokens.append('""')
            tokens.append(char)
            previous_was_escape = False
        else:
            tokens.append(f"\\x{byte:02x}")
            previous_was_escape = True

    return tokens


def emit_literal(data: bytes, indent: str = "    ") -> str:
    tokens = string_tokens(data)
    lines: list[str] = []
    current = ""
    for token in tokens:
        if len(current) + len(token) > 100:
            lines.append(current)
            current = ""
        current += token
    if current:
        lines.append(current)

    body = "\n".join(f'{indent}"{line}"' for line in lines)
    return body + ";"


def main() -> None:
    parts: list[str] = []
    parts.append("// Generated by tools/gen_assets.py - do not edit by hand.")
    parts.append("// Source files live in the web/ directory.")
    parts.append('#include "static_assets.h"')
    parts.append("")
    parts.append("namespace fsrv {")
    parts.append("namespace {")
    parts.append("")

    names: list[str] = []
    for index, (_, filename, _) in enumerate(ASSETS):
        data = (ROOT / "web" / filename).read_bytes()
        name = f"kAsset{index}"
        parts.append(f"const char {name}[] =")
        parts.append(emit_literal(data))
        parts.append("")
        names.append(name)

    parts.append("const StaticAsset kAssets[] = {")
    for (path, _, content_type), name in zip(ASSETS, names):
        parts.append(f'    {{"{path}", "{content_type}", {name}, sizeof({name}) - 1}},')
    parts.append("};")
    parts.append("")
    parts.append("}  // namespace")
    parts.append("")
    parts.append("const StaticAsset* find_static_asset(std::string_view path) {")
    parts.append("  for (const auto& asset : kAssets) {")
    parts.append("    if (path == asset.path) return &asset;")
    parts.append("  }")
    parts.append("  return nullptr;")
    parts.append("}")
    parts.append("")
    parts.append("}  // namespace fsrv")
    parts.append("")

    OUTPUT.write_text("\n".join(parts), encoding="utf-8", newline="\n")
    total = sum((ROOT / "web" / f).stat().st_size for _, f, _ in ASSETS)
    print(f"wrote {OUTPUT} ({total} bytes of assets embedded)")


if __name__ == "__main__":
    main()
